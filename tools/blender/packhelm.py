# The helmets' and masks' maps (helmsheets.py's colour, roughness, metalness and masks; helmbake.py's normal map and
# occlusion) packed as WebP into src/helmmaps-data.js. Plain Python 3 (numpy, Pillow).
#
#   python3 tools/blender/packhelm.py <bake dir> [--preview]
#
# Each sheet: `albedo` RGB with the occlusion multiplied in (A: the lacquer mask, where the mask's colour is the wearer's),
# `normal` RGB (A: the cut-out, where a mask's outline is), `orm` (R occlusion, G roughness, B metalness) at half size;
# a mask also carries its mesh's relief lattice (`grid`).

import base64
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pack import normals, resample, to8, webp  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHEETS = {
    'helmBrim': {'size': 512}, 'helmBrimThraex': {'size': 512}, 'helmBrimMurmillo': {'size': 512},
    'helmSecutor': {'size': 512}, 'helmScissor': {'size': 512},
    'maskOni': {'size': 512, 'alpha': True}, 'maskRessei': {'size': 512, 'alpha': True}, 'maskTengu': {'size': 512, 'alpha': True},
}
QUALITY = {'albedo': 84, 'normal': 86, 'orm': 78}
AO_IN_ALBEDO = 0.7


def load(folder, name, key):
    return np.load(os.path.join(folder, f'{name}_{key}.npy'))


def pack(folder, name, spec, preview):
    size = spec['size']
    n = normals(load(folder, name, 'normal'), size)
    ao = load(folder, name, 'orm')[:, :, 0:1]
    colour = load(folder, name, 'src_alb') * (1 - AO_IN_ALBEDO * (1 - ao))
    colour = resample(colour, size)
    rough = load(folder, name, 'src_rough')[:, :, None]
    metal = load(folder, name, 'src_metal')[:, :, None]
    orm = resample(np.concatenate([ao, rough, metal], axis=2), size // 2)
    out = {}
    if spec.get('alpha'):
        lacquer = resample(load(folder, name, 'src_mask')[:, :, None], size)
        cut = resample(load(folder, name, 'src_cut')[:, :, None], size)
        out['albedo'] = webp(to8(np.concatenate([colour, lacquer], axis=2)), QUALITY['albedo'])
        out['normal'] = webp(to8(np.concatenate([n, cut], axis=2)), QUALITY['normal'])
    else:
        out['albedo'] = webp(to8(colour), QUALITY['albedo'])
        out['normal'] = webp(to8(n), QUALITY['normal'])
    out['orm'] = webp(to8(orm), QUALITY['orm'])
    if preview:
        for key, data in out.items():
            with open(os.path.join(folder, f'{name}.{key}.webp'), 'wb') as file:
                file.write(data)
    mean = [round(float(v), 4) for v in to8(colour).reshape(-1, 3).mean(axis=0) / 255]
    entry = {'size': [size, size], 'mean': mean, **{key: base64.b64encode(data).decode('ascii') for key, data in out.items()}}
    grid = os.path.join(folder, f'{name}_grid.json')
    if os.path.exists(grid):
        with open(grid) as file:
            entry['grid'] = json.load(file)
    print(name, {key: len(data) for key, data in out.items()}, 'bytes', flush=True)
    return entry


def main():
    folder = sys.argv[1]
    preview = '--preview' in sys.argv
    entries = {name: pack(folder, name, spec, preview) for name, spec in SHEETS.items()}
    total = sum(len(base64.b64decode(entry[key])) for entry in entries.values() for key in ('albedo', 'normal', 'orm'))
    print('total WebP bytes', total)
    if preview:
        return
    lines = [
        '// Generated by tools/blender/packhelm.py from the sheets authored by helmsheets.py and baked in Blender by helmbake.py.',
        "// Do not edit. Each: the size in pixels, the albedo's mean colour (0..1), the WebP images (base64): `albedo` RGB with the",
        "// occlusion in (A: a mask's lacquer, drawn in the wearer's colour), `normal` tangent space, OpenGL (A: a mask's cut-out),",
        "// `orm` occlusion, roughness, metalness; a mask's `grid`: its mesh's relief (src/menpo.js).",
        'export const HELM_MAP_DATA = {',
    ]
    for name, entry in entries.items():
        lines.append(f'  {name}: {{')
        lines.append(f"    size: {json.dumps(entry['size'])}, mean: {json.dumps(entry['mean'])},")
        if 'grid' in entry:
            lines.append(f"    grid: {json.dumps(entry['grid'], separators=(',', ':'))},")
        for key in ('albedo', 'normal', 'orm'):
            lines.append(f"    {key}: '{entry[key]}',")
        lines.append('  },')
    lines.append('};')
    with open(os.path.join(ROOT, 'src', 'helmmaps-data.js'), 'w') as file:
        file.write('\n'.join(lines) + '\n')
    print('wrote src/helmmaps-data.js')


if __name__ == '__main__':
    main()
