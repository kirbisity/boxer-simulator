# Turn a baked tile's float maps (<dir>/<name>_<mode>.npy, from tilebake.py) into the images the game embeds, and
# write them into src/detailmaps-data.js (base64 WebP). Plain Python 3 with numpy and Pillow (built with WebP).
#
#   python3 tools/blender/pack.py <bake dir> [--preview]
#
# What each map becomes (all WebP; `quality` per map below, lossy but high):
#   <name>.normal  the tangent-space normal (OpenGL: green up), renormalised.
#   <name>.albedo  the base colour, with the occlusion multiplied in where the surface has no second set of UVs
#                  (`ao_in_albedo`), else as it is.
#   <name>.orm     R occlusion, G roughness, B metalness (three's aoMap reads R, roughnessMap G, metalnessMap B).
#   <name>.mask    (lamellae) where the lace colour shows, in the albedo's alpha instead when `mask_in_alpha`.

import base64
import io
import json
import os
import sys

import numpy as np
from PIL import Image

# name: (quality, ao_in_albedo, ao strength in albedo, mask_in_alpha)
MAPS = {
    'mail': {'quality': 92, 'ao_in_albedo': False, 'mask': False},
    'lamellae': {'quality': 92, 'ao_in_albedo': False, 'mask': True},
    'ashlar': {'quality': 90, 'ao_in_albedo': True, 'ao_strength': 0.85, 'mask': False},
    'cobble': {'quality': 90, 'ao_in_albedo': True, 'ao_strength': 0.85, 'mask': False},
}

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load(folder, name, mode):
    path = os.path.join(folder, f'{name}_{mode}.npy')
    return np.load(path) if os.path.exists(path) else None


def to8(array):
    return (np.clip(array, 0, 1) * 255 + 0.5).astype(np.uint8)


def webp(array, quality, mode='RGB'):
    image = Image.fromarray(array, mode)
    buffer = io.BytesIO()
    image.save(buffer, 'WEBP', quality=quality, method=6, exact=True)
    return buffer.getvalue()


def pack(folder, name, spec, preview):
    normal = load(folder, name, 'normal')
    albedo = load(folder, name, 'albedo')
    orm = load(folder, name, 'orm')
    if normal is None or albedo is None or orm is None:
        return None
    n = normal * 2 - 1
    n /= np.maximum(np.linalg.norm(n, axis=2, keepdims=True), 1e-6)
    normal8 = to8(n * 0.5 + 0.5)
    ao = orm[:, :, 0:1]
    colour = albedo * (1 - spec.get('ao_strength', 1) * (1 - ao)) if spec['ao_in_albedo'] else albedo
    colour8 = to8(colour)
    out = {}
    if spec['mask']:
        mask = load(folder, name, 'mask')
        alpha = to8(mask[:, :, 0:1])
        out['albedo'] = webp(np.concatenate([colour8, alpha], axis=2), spec['quality'], 'RGBA')
    else:
        out['albedo'] = webp(colour8, spec['quality'])
    out['normal'] = webp(normal8, spec['quality'])
    out['orm'] = webp(to8(orm), spec['quality'])
    if preview:
        for key, data in out.items():
            with open(os.path.join(folder, f'{name}.{key}.webp'), 'wb') as file:
                file.write(data)
        Image.fromarray(normal8).save(os.path.join(folder, f'{name}.normal.png'))
        Image.fromarray(colour8).save(os.path.join(folder, f'{name}.albedo.png'))
        Image.fromarray(to8(orm)).save(os.path.join(folder, f'{name}.orm.png'))
    h, w = normal8.shape[:2]
    mean = [round(float(value), 4) for value in colour8.reshape(-1, 3).mean(axis=0) / 255]
    return {'size': [w, h], 'mean': mean, **{key: base64.b64encode(data).decode('ascii') for key, data in out.items()}}


def main():
    folder = sys.argv[1]
    preview = '--preview' in sys.argv
    entries = {}
    for name, spec in MAPS.items():
        packed = pack(folder, name, spec, preview)
        if packed:
            entries[name] = packed
            sizes = {key: len(value) * 3 // 4 for key, value in packed.items() if key not in ('size', 'mean')}
            print(name, packed['size'], sizes)
    if preview:
        return
    lines = [
        '// Generated by tools/blender/pack.py from the tiles baked in Blender (tools/blender/*.py). Do not edit.',
        '// Each: the size in pixels, the albedo\'s mean colour (0..1), and WebP images (base64): `albedo` (RGB, or RGBA with the lace mask in alpha), `normal` (tangent',
        '// space, OpenGL: green up), `orm` (R occlusion, G roughness, B metalness).',
        'export const DETAIL_MAP_DATA = {',
    ]
    for name, entry in entries.items():
        lines.append(f'  {name}: {{')
        lines.append(f"    size: {json.dumps(entry['size'])}, mean: {json.dumps(entry['mean'])},")
        for key in ('albedo', 'normal', 'orm'):
            lines.append(f"    {key}: '{entry[key]}',")
        lines.append('  },')
    lines.append('};')
    with open(os.path.join(ROOT, 'src', 'detailmaps-data.js'), 'w') as file:
        file.write('\n'.join(lines) + '\n')
    print('wrote src/detailmaps-data.js')


if __name__ == '__main__':
    main()
