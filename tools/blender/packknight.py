# The knights' helmets' maps (knighthelms.py's colour, roughness, metalness and cut-out; helmbake.py's normal map and
# occlusion) packed as WebP into src/knighthelms-data.js, as packhelm.py packs the other helmets' (its `pack`). A sheet not
# baked in the folder keeps the entry it has. Plain Python 3 (numpy, Pillow).
#
#   python3 tools/blender/packknight.py <bake dir> [--preview]

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from packhelm import pack  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'src', 'knighthelms-data.js')
SHEETS = {name: {'size': 512, 'cut': True} for name in (
    'knightGreatHelm', 'knightHounskull', 'knightGreatBascinet', 'knightArmet', 'knightSallet', 'knightCloseHelmet')}


def kept(name):
    """A sheet's lines as src/knighthelms-data.js has them now, or None."""
    with open(OUT) as file:
        text = file.read()
    marker = f'\n  {name}: {{\n'
    if marker not in text:
        return None
    start = text.index(marker) + 1
    end = text.index('\n  },\n', start) + len('\n  },')
    return text[start:end]


def main():
    folder = sys.argv[1]
    preview = '--preview' in sys.argv
    baked = {name: spec for name, spec in SHEETS.items() if os.path.exists(os.path.join(folder, f'{name}_normal.npy'))}
    entries = {name: pack(folder, name, spec, preview) for name, spec in baked.items()}
    if preview:
        return
    lines = [
        '// Generated by tools/blender/packknight.py from the sheets authored by knighthelms.py, baked by helmbake.py. Do not edit.',
        "// Each: the size in pixels, the albedo's mean colour (0..1), the WebP images (base64): `albedo` RGB with the occlusion",
        "// in, `normal` tangent space, OpenGL (A: the cut-out: the sights, breaths and face openings), `orm` occlusion, roughness,",
        '// metalness. knighthelms.js adds them to the helmets\' sheets (helmmaps-data.js HELM_MAP_DATA).',
        'export const KNIGHT_HELM_MAP_DATA = {',
    ]
    for name in SHEETS:
        if name not in entries:
            old = kept(name)
            if old:
                lines.append(old)
            continue
        entry = entries[name]
        lines.append(f'  {name}: {{')
        lines.append(f"    size: {json.dumps(entry['size'])}, mean: {json.dumps(entry['mean'])},")
        for key in ('albedo', 'normal', 'orm'):
            lines.append(f"    {key}: '{entry[key]}',")
        lines.append('  },')
    lines.append('};')
    with open(OUT, 'w') as file:
        file.write('\n'.join(lines) + '\n')
    print('wrote src/knighthelms-data.js')


if __name__ == '__main__':
    main()
