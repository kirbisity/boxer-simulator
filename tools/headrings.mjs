// The head model's jaw line and the ring of the scan's neck under it, for the base body's neck to meet the head
// (src/basebody.js headJawLine, neckUnderHead): the lattice's rings at HEAD_LATTICE.lid and BASE_BODY.neckUnder.throat, on
// the head of no particular face, in the model's unit space (the skull's proportions taken off), a sex at a time.
// Run again when the head model (src/headgrid-data.js), its lid or the throat's row change; test/headlattice.test.js checks
// the file against the model.
//   node tools/headrings.mjs > src/headrings-data.js
import { HEAD_LATTICE, buildLatticeHead, headLattice } from '../src/headlattice.js';
import { HEAD_GRID_DATA } from '../src/headgrid-data.js';
import { BASE_BODY, HEAD_SKULL } from '../src/basebody.js';

// The photo atlas' marks (src/photoface.js PHOTO_ATLAS, which needs three.js; test/headlattice.test.js checks the copy there).
export const HEAD_ATLAS = { eyeU: 0.0668, earU: 0.258, eyeRow: 0.44, mouthRow: 0.7, chinRow: 0.88, mouthShare: 0.56, chinT: 0.95, hairlineRow: 0.22, hairlineAt: 0.36, eyeHalf: [0.027, 0.013] };

/** Each sex's two rings: [[x, y, z], ...] round the head, the jaw line's and the throat's. */
export function headRings() {
  const out = {};
  for (const sex of ['male', 'female']) {
    const lattice = headLattice(HEAD_GRID_DATA, sex);
    const head = buildLatticeHead({ data: HEAD_GRID_DATA, radius: 1, skull: HEAD_SKULL, shape: {}, atlas: HEAD_ATLAS, female: sex === 'female', lid: false });
    const stride = head.positions.length / 3 / lattice.rows.length;
    const ringAt = (wanted) => {
      const row = lattice.rows.reduce((best, value, index) => (Math.abs(value - wanted) < Math.abs(lattice.rows[best] - wanted) ? index : best), 0);
      return Array.from({ length: stride }, (_, column) => [0, 1, 2].map((axis) => Math.round((head.positions[(row * stride + column) * 3 + axis] / HEAD_SKULL[axis]) * 1e4) / 1e4));
    };
    out[sex] = { jaw: ringAt(HEAD_LATTICE.lid), throat: ringAt(BASE_BODY.neckUnder.throat) };
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rings = headRings();
  const lines = ['// Generated by tools/headrings.mjs; do not edit by hand.', '// The head model\'s jaw line and the scan\'s neck\'s ring under it, a sex at a time (src/basebody.js headJawLine).', 'export const HEAD_RINGS = {'];
  for (const [sex, { jaw, throat }] of Object.entries(rings)) lines.push(`  ${sex}: {`, `    jaw: ${JSON.stringify(jaw.flat())},`, `    throat: ${JSON.stringify(throat.flat())},`, '  },');
  lines.push('};', '');
  process.stdout.write(lines.join('\n'));
}
