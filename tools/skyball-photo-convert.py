# Turn Poly Haven tonemapped panoramas (CC0, see docs/credits-scenery-photo.md)
# into src/scenery/skyball-photo-data.js for the skyball-photo scenery variant.
#
# Each equirectangular picture becomes two JPEGs: a sharp band round the
# horizon (where the landscape is) and a small sky cap above it, plus the
# picture's horizon colour and where its sun stands (u, 0..1 across).
#
#   python3 tools/skyball-photo-convert.py src/scenery/skyball-photo-data.js \
#       meadow=evening_meadow.jpg plain=kiara_5_noon.jpg valley=alps_field.jpg
#
# Run once; the output is committed. Needs Pillow.

import base64
import io
import sys

from PIL import Image, ImageFilter

Image.MAX_IMAGE_PIXELS = None

BAND = {'low': -12.0, 'high': 24.0, 'width': 4096, 'quality': 72}
SKY = {'low': 20.0, 'high': 90.0, 'width': 1024, 'quality': 70}


def row_of(elevation, height):
    return (90.0 - elevation) / 180.0 * height


def cut(image, part):
    width, height = image.size
    top, bottom = row_of(part['high'], height), row_of(part['low'], height)
    rows = round((part['high'] - part['low']) / 360.0 * part['width'])
    piece = image.crop((0, int(top), width, int(round(bottom)))).resize((part['width'], rows), Image.LANCZOS)
    buffer = io.BytesIO()
    piece.save(buffer, 'JPEG', quality=part['quality'], optimize=True, progressive=True)
    return {'low': part['low'], 'high': part['high'], 'jpeg': base64.b64encode(buffer.getvalue()).decode('ascii')}, len(buffer.getvalue())


def sun_u(image):
    small = image.resize((512, 256), Image.BILINEAR).convert('L').filter(ImageFilter.GaussianBlur(3))
    pixels = small.load()
    best, at = -1, 0
    for y in range(0, 120):
        for x in range(512):
            if pixels[x, y] > best:
                best, at = pixels[x, y], x
    return (at + 0.5) / 512


def horizon_colour(image):
    # The median colour just above the picture's horizon, all the way round.
    width, height = image.size
    strip = image.crop((0, int(row_of(1.5, height)), width, int(row_of(-0.5, height)))).resize((512, 4), Image.BILINEAR)
    channels = list(zip(*strip.getdata()))
    return [sorted(channel)[len(channel) // 2] / 255 for channel in channels]


def main(out, entries):
    lines = [
        '// Generated by tools/skyball-photo-convert.py from Poly Haven panoramas (CC0, see docs/credits-scenery-photo.md). Do not edit.',
        '// Each: a sharp JPEG band round the horizon and a small sky cap (equirectangular, elevations in degrees),',
        '// the horizon colour (0..1) and the sun\'s place across the picture (u, 0..1).',
        'export const SKYBALL_PHOTO_DATA = {',
    ]
    total = 0
    for entry in entries:
        name, source = entry.split('=', 1)
        image = Image.open(source).convert('RGB')
        band, band_bytes = cut(image, BAND)
        sky, sky_bytes = cut(image, SKY)
        total += band_bytes + sky_bytes
        horizon = [round(c, 3) for c in horizon_colour(image)]
        sun = round(sun_u(image), 4)
        print(f'{name}: band {band_bytes} B, sky {sky_bytes} B, horizon {horizon}, sun u {sun}')
        lines.append(f'  {name}: {{')
        lines.append(f'    horizon: {horizon}, sunU: {sun},')
        for label, part in (('band', band), ('sky', sky)):
            lines.append(f"    {label}: {{ low: {part['low']}, high: {part['high']}, jpeg: '{part['jpeg']}' }},")
        lines.append('  },')
    lines.append('};')
    with open(out, 'w') as handle:
        handle.write('\n'.join(lines) + '\n')
    print(f'total JPEG {total} B')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
